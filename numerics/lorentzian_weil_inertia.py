"""Finite-dimensional Weil-form inertia experiments.

The test space is generated by translates of a normalized centered cubic
B-spline.  For support radius T and dimension N, put

    w = 2T/(N+3),  c_j = -T + 2w + jw,  0 <= j < N,
    g_j(x) = w^{-1} B_4((x-c_j)/w).

Every g_j is supported in [-T,T].  With
F_j(t) = integral g_j(x) exp(itx) dx, the Gram entries are evaluated from
the Guinand-Weil explicit formula, not from zeros.  The prime-power sum is
finite because correlations are supported in [-2T,2T].
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path

import numpy as np
from scipy import integrate, interpolate, linalg, special


NUMERICS = Path(__file__).resolve().parent
ZERO_FILE = NUMERICS / "zeta_first_200_zeros.csv"

T_VALUES = (0.15, 0.25, 0.35, 0.50, 0.75, 1.00, 1.50, 2.00, 3.00)
N_VALUES = (4, 8, 16, 24, 32, 48, 64)

_B8_SPLINE = interpolate.BSpline.basis_element(
    np.arange(9, dtype=float), extrapolate=False
)


def centered_bspline_8(x: float) -> float:
    """Centered cardinal B-spline of order 8, supported on [-4,4]."""
    return float(np.nan_to_num(_B8_SPLINE(x + 4.0), nan=0.0))


def von_mangoldt_table(limit: int) -> np.ndarray:
    """Return Lambda(n), 0 <= n <= limit, by an Eratosthenes sieve."""
    values = np.zeros(limit + 1, dtype=float)
    is_prime = np.ones(limit + 1, dtype=bool)
    is_prime[: min(2, limit + 1)] = False
    for p in range(2, limit + 1):
        if not is_prime[p]:
            continue
        if p * p <= limit:
            is_prime[p * p :: p] = False
        power = p
        while power <= limit:
            values[power] = math.log(p)
            power *= p
    return values


def archimedean_entry(w: float, lag: int, ymax: float, eps: float) -> tuple[float, float]:
    r"""Compute

      (1/2pi) int_R exp(i t lag w) sinc(wt/2)^8
              (Re psi(1/4+it/2)-log pi) dt.

    The change of variables y=wt/2 makes the oscillation cos(2 lag y).
    """

    def amplitude(y: float) -> float:
        sinc = 1.0 if y == 0.0 else math.sin(y) / y
        return sinc**8 * (
            special.digamma(0.25 + 1j * y / w).real - math.log(math.pi)
        )

    if lag == 0:
        value, error = integrate.quad(
            amplitude,
            0.0,
            ymax,
            points=np.arange(math.pi, ymax, math.pi),
            epsabs=eps,
            epsrel=eps,
            limit=1200,
        )
    else:
        value, error = integrate.quad(
            amplitude,
            0.0,
            ymax,
            weight="cos",
            wvar=2.0 * lag,
            epsabs=eps,
            epsrel=eps,
            limit=1200,
            maxp1=400,
        )
    factor = 2.0 / (math.pi * w)
    return factor * value, factor * error


def gram_components(
    T: float, N: int, ymax: float = 100.0, eps: float = 2e-11
) -> dict[str, np.ndarray | float | int]:
    """Build the explicit-formula Gram matrix and its three components."""
    w = 2.0 * T / (N + 3)
    max_n = int(math.floor(math.exp(2.0 * T + 1e-13)))
    mangoldt = von_mangoldt_table(max_n)
    prime_powers = np.flatnonzero(mangoldt)
    prime_powers = prime_powers[prime_powers >= 2]

    full_entries: list[float] = []
    pole_entries: list[float] = []
    arch_entries: list[float] = []
    prime_entries: list[float] = []
    quadrature_errors: list[float] = []

    sinhc = math.sinh(w / 4.0) / (w / 4.0)
    for lag in range(N):
        displacement = lag * w
        arch, arch_error = archimedean_entry(w, lag, ymax, eps)
        pole = 2.0 * math.cosh(displacement / 2.0) * sinhc**8
        prime = 0.0
        for n in prime_powers:
            u = math.log(int(n))
            correlation = (
                centered_bspline_8((u - displacement) / w)
                + centered_bspline_8((-u - displacement) / w)
            ) / w
            prime += mangoldt[n] * correlation / math.sqrt(float(n))

        full_entries.append(pole + arch - prime)
        pole_entries.append(pole)
        arch_entries.append(arch)
        prime_entries.append(prime)
        quadrature_errors.append(arch_error)

    l2_entries = [centered_bspline_8(-lag) / w for lag in range(N)]
    return {
        "W": linalg.toeplitz(full_entries),
        "P": linalg.toeplitz(pole_entries),
        "A": linalg.toeplitz(arch_entries),
        "R": linalg.toeplitz(prime_entries),
        "L2": linalg.toeplitz(l2_entries),
        "w": w,
        "max_n": max_n,
        "prime_power_count": len(prime_powers),
        "quad_error_bound": N * max(quadrature_errors, default=0.0),
    }


def inertia(eigenvalues: np.ndarray, relative_tolerance: float = 1e-9) -> tuple[int, int, int, float]:
    scale = max(float(np.max(np.abs(eigenvalues))), 1.0)
    tolerance = relative_tolerance * scale
    positive = int(np.count_nonzero(eigenvalues > tolerance))
    negative = int(np.count_nonzero(eigenvalues < -tolerance))
    zero = len(eigenvalues) - positive - negative
    return positive, negative, zero, tolerance


def zero_side_entries(T: float, N: int) -> np.ndarray:
    """First-200-zero cross-check.  This is not used to build W."""
    ordinates: list[float] = []
    with ZERO_FILE.open(newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            ordinates.append(float(row["ordinate"]))
    w = 2.0 * T / (N + 3)
    entries = []
    for lag in range(N):
        d = lag * w
        value = 0.0
        for gamma in ordinates:
            y = w * gamma / 2.0
            sinc = math.sin(y) / y
            value += 2.0 * math.cos(gamma * d) * sinc**8
        entries.append(value)
    return np.asarray(entries)


def run() -> None:
    output_rows: list[dict[str, str | int | float]] = []
    component_rows: list[dict[str, str | int | float]] = []

    for T in T_VALUES:
        for N in N_VALUES:
            components = gram_components(T, N)
            W = np.asarray(components["W"])
            P = np.asarray(components["P"])
            L2 = np.asarray(components["L2"])
            reduced = W - P

            raw_eigenvalues = np.linalg.eigvalsh(W)
            generalized = linalg.eigh(W, L2, eigvals_only=True)
            p, m, z, tolerance = inertia(raw_eigenvalues)
            rp, rm, rz, reduced_tolerance = inertia(np.linalg.eigvalsh(reduced))

            zero_entries = zero_side_entries(T, N)
            explicit_entries = W[0, :]
            crosscheck = float(np.max(np.abs(explicit_entries - zero_entries)))

            output_rows.append(
                {
                    "T": T,
                    "N": N,
                    "width_w": components["w"],
                    "max_prime_power_n": components["max_n"],
                    "prime_power_count": components["prime_power_count"],
                    "n_positive": p,
                    "n_negative": m,
                    "n_numerical_zero": z,
                    "raw_lambda_min": raw_eigenvalues[0],
                    "raw_lambda_max": raw_eigenvalues[-1],
                    "generalized_lambda_min": generalized[0],
                    "generalized_lambda_max": generalized[-1],
                    "generalized_gap_ratio": generalized[0] / generalized[-1],
                    "inertia_tolerance": tolerance,
                    "quadrature_error_bound": components["quad_error_bound"],
                    "first_200_zero_max_entry_difference": crosscheck,
                }
            )
            component_rows.append(
                {
                    "T": T,
                    "N": N,
                    "form": "W-full",
                    "n_positive": p,
                    "n_negative": m,
                    "n_numerical_zero": z,
                    "tolerance": tolerance,
                }
            )
            component_rows.append(
                {
                    "T": T,
                    "N": N,
                    "form": "P-poles",
                    "n_positive": inertia(np.linalg.eigvalsh(P))[0],
                    "n_negative": inertia(np.linalg.eigvalsh(P))[1],
                    "n_numerical_zero": inertia(np.linalg.eigvalsh(P))[2],
                    "tolerance": inertia(np.linalg.eigvalsh(P))[3],
                }
            )
            component_rows.append(
                {
                    "T": T,
                    "N": N,
                    "form": "W-minus-P",
                    "n_positive": rp,
                    "n_negative": rm,
                    "n_numerical_zero": rz,
                    "tolerance": reduced_tolerance,
                }
            )

    inertia_path = NUMERICS / "weil_spline_inertia.csv"
    with inertia_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(output_rows[0]))
        writer.writeheader()
        writer.writerows(output_rows)

    components_path = NUMERICS / "weil_component_signatures.csv"
    with components_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(component_rows[0]))
        writer.writeheader()
        writer.writerows(component_rows)

    summary = {
        "basis": "centered cubic B-spline translates",
        "T_values": T_VALUES,
        "N_values": N_VALUES,
        "rows": len(output_rows),
        "full_form_negative_indices": sorted({int(row["n_negative"]) for row in output_rows}),
        "reduced_form_negative_indices": sorted(
            {
                int(row["n_negative"])
                for row in component_rows
                if row["form"] == "W-minus-P"
            }
        ),
        "files": [inertia_path.name, components_path.name],
    }
    (NUMERICS / "lorentzian_weil_summary.json").write_text(
        json.dumps(summary, indent=2), encoding="utf-8"
    )


